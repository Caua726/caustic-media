#!/usr/bin/env python3
# text/tools/make_arabic_forms.py — text/shape/arabic_forms.cst: which of
# Unicode's Arabic presentation forms draws a letter in each joining form, for a
# font that has them and none of the features. From the compatibility
# decompositions of Python's own Unicode data, which must be the version
# caustic-unicode's tables are of.
#
#   python3 text/tools/make_arabic_forms.py
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "shape", "arabic_forms.cst")
assert unicodedata.unidata_version.startswith("16."), unicodedata.unidata_version

ORDER = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
forms = {}
lam_alef = {}
shadda = []
for block in (range(0xFB50, 0xFE00), range(0xFE70, 0xFEFF)):
    for u in block:
        d = unicodedata.decomposition(chr(u)).split()
        if len(d) < 2 or d[0] not in ORDER:
            continue
        parts = [int(x, 16) for x in d[1:]]
        if len(parts) == 1:
            forms.setdefault(parts[0], [0, 0, 0, 0])
            if forms[parts[0]][ORDER[d[0]]] == 0:
                forms[parts[0]][ORDER[d[0]]] = u
        elif len(parts) == 2 and parts[0] == 0x644 and u >= 0xFEF5:
            lam_alef.setdefault(parts[1], [0, 0])[ORDER[d[0]]] = u
        elif len(parts) == 3 and parts[0] == 0x20 and parts[2] == 0x651:
            shadda.append((parts[1], u))


def hex4(v):
    return "%04X" % v


out = ["// text/shape/arabic_forms.cst — generated by text/tools/make_arabic_forms.py from",
       "// Unicode's decompositions. Do not edit.",
       "",
       "let is i64 as FORMS_COUNT with imut = %d;" % len(forms),
       "// A letter, then the characters of its isolated, final, initial and medial forms;",
       "// 0000 for none. Sorted; four hexadecimal digits each.",
       'let is *u8 as FORMS with imut = "%s";' % "".join(hex4(u) + "".join(hex4(f) for f in forms[u]) for u in sorted(forms)),
       "",
       "let is i64 as LAM_ALEF_COUNT with imut = %d;" % len(lam_alef),
       "// An alef, then the characters of lam and it as one, isolated and final.",
       'let is *u8 as LAM_ALEF with imut = "%s";' % "".join(hex4(u) + hex4(lam_alef[u][0]) + hex4(lam_alef[u][1]) for u in sorted(lam_alef)),
       "",
       "let is i64 as SHADDA_COUNT with imut = %d;" % len(shadda),
       "// A mark, then the character of it and shadda as one.",
       'let is *u8 as SHADDA with imut = "%s";' % "".join(hex4(a) + hex4(b) for a, b in sorted(shadda)),
       ""]
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print(os.path.basename(OUT), len(forms), "letters", len(lam_alef), "alefs", len(shadda), "marks")
