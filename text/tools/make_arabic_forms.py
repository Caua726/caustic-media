#!/usr/bin/env python3
# text/tools/make_arabic_forms.py — text/shape/arabic_forms.cst: which of
# Unicode's Arabic presentation forms draws a letter in each joining form, for a
# font that has them and none of the features. From the compatibility
# decompositions of Python's own Unicode data, which must be the version
# caustic-unicode's tables are of.
#
#   python3 text/tools/make_arabic_forms.py
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "shape", "arabic_forms.cst")
assert unicodedata.unidata_version.startswith("16."), unicodedata.unidata_version

ORDER = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
# Not every ligature Unicode has: most are a calligrapher's choice. Those that a
# font with nothing else is drawn with, as HarfBuzz draws it, found by shaping each
# with it; and two of the private use area of old fonts, found the same way, which
# Unicode knows nothing of.
WANTED = set(int(x, 16) for x in """
    FC08 FC0E FC12 FC32 FC3F FC40 FC41 FC42 FC43 FC44 FC4E FC5E FC60 FC61 FC62 FC6A FC6D FC6F FC70 FC73 FC75
    FC86 FC8F FC91 FC94 FC9C FC9D FC9E FC9F FCA1 FCA2 FCA3 FCA4 FCA8 FCAA FCAC FCB0 FCC9 FCCA FCCB FCCC FCCD
    FCCE FCCF FCD0 FCD1 FCD2 FCD3 FCD5 FCDA FCDB FCDC FCDD FD30 FEF5 FEF6 FEF7 FEF8 FEF9 FEFA FEFB FEFC""".split())
PRIVATE = {(0x644, 0x644, 0x647, 0): 0xF201, (0x644, 0x645, 0x62C, 2): 0xF211}
forms = {}
ligatures = dict(PRIVATE)
shadda = []
for block in (range(0xFB50, 0xFE00), range(0xFE70, 0xFEFF)):
    for u in block:
        d = unicodedata.decomposition(chr(u)).split()
        if len(d) < 2 or d[0] not in ORDER:
            continue
        parts = [int(x, 16) for x in d[1:]]
        if len(parts) == 1:
            forms.setdefault(parts[0], [0, 0, 0, 0])
            if forms[parts[0]][ORDER[d[0]]] == 0:
                forms[parts[0]][ORDER[d[0]]] = u
        elif u not in WANTED:
            continue
        elif len(parts) == 3 and parts[0] == 0x20 and parts[2] == 0x651:
            shadda.append((parts[1], u))
        elif len(parts) <= 3 and all(unicodedata.category(chr(p)) == "Lo" for p in parts):
            ligatures.setdefault((parts[0], parts[1], parts[2] if len(parts) == 3 else 0, ORDER[d[0]]), u)


def hex4(v):
    return "%04X" % v


out = ["// text/shape/arabic_forms.cst — generated by text/tools/make_arabic_forms.py from",
       "// Unicode's decompositions. Do not edit.",
       "",
       "let is i64 as FORMS_COUNT with imut = %d;" % len(forms),
       "// A letter, then the characters of its isolated, final, initial and medial forms;",
       "// 0000 for none. Sorted; four hexadecimal digits each.",
       'let is *u8 as FORMS with imut = "%s";' % "".join(hex4(u) + "".join(hex4(f) for f in forms[u]) for u in sorted(forms)),
       "",
       "let is i64 as LIGATURES_COUNT with imut = %d;" % len(ligatures),
       "// Two letters or three (0000 for no third), the form the whole is in, 0 isolated,",
       "// 1 final, 2 initial, 3 medial, and its character. Sorted by the first.",
       'let is *u8 as LIGATURES with imut = "%s";' % "".join(hex4(k[0]) + hex4(k[1]) + hex4(k[2]) + hex4(k[3]) + hex4(ligatures[k]) for k in sorted(ligatures)),
       "",
       "let is i64 as SHADDA_COUNT with imut = %d;" % len(shadda),
       "// A mark, then the character of it and shadda as one.",
       'let is *u8 as SHADDA with imut = "%s";' % "".join(hex4(a) + hex4(b) for a, b in sorted(shadda)),
       ""]
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print(os.path.basename(OUT), len(forms), "letters", len(ligatures), "ligatures", len(shadda), "marks")
