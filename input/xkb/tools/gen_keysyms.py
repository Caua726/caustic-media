#!/usr/bin/env python3
"""Generate input/xkb/keysyms.cst: keysym names, characters and case.

    python3 input/xkb/tools/gen_keysyms.py \
        [--header /usr/include/xkbcommon/xkbcommon-keysyms.h] \
        [--unicode-data /usr/share/texmf-dist/tex/generic/unicode-data/UnicodeData.txt]

The names and values are xkbcommon-keysyms.h's #defines; a keysym's
character is the "U+XXXX" its comment gives (bare, parenthesized or angled
alike), for every name of that value. Case comes from UnicodeData.txt's
simple mappings: a code point's, and a legacy keysym's through its character
back to the first legacy keysym of the mapped character (a Unicode keysym
when there is none). input/xkb/xkb_test.cst checks the result against the
installed libxkbcommon keysym by keysym.
"""
import argparse
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# What libxkbcommon's tables say that the header's comments do not: the
# angle brackets' current characters (the header names the deprecated
# U+2329/U+232A), the XF86 numeric keypad keysyms' characters, and the
# capital sharp s as ssharp's upper case.
UCS_OVERRIDES = {0xabc: 0x27e8, 0xabe: 0x27e9}
UCS_OVERRIDES.update({0x10081200 + d: 0x30 + d for d in range(10)})
UCS_OVERRIDES.update({0x1008120a: 0x2a, 0x1008120b: 0x23})
UPPER_OVERRIDES = {0xdf: 0x1001e9e}

LEGACY_CASE_MAX = 0x13be
UNICODE_OFFSET = 0x1000000


def rule_ucs(ks):
    """The character libxkbcommon gives by rule, before its table; None to look."""
    if 0x20 <= ks <= 0x7e or 0xa0 <= ks <= 0xff:
        return ks
    if ks == 0xff80:
        return 0x20
    if 0xff08 <= ks <= 0xff0b or 0xffaa <= ks <= 0xffb9 or ks in (0xff0d, 0xff1b, 0xffff, 0xff89, 0xff8d, 0xffbd):
        return ks & 0x7f
    if 0x100d800 <= ks <= 0x100dfff:
        return 0
    if UNICODE_OFFSET <= ks <= 0x110ffff:
        return ks - UNICODE_OFFSET
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--header', default='/usr/include/xkbcommon/xkbcommon-keysyms.h')
    ap.add_argument('--unicode-data', default='/usr/share/texmf-dist/tex/generic/unicode-data/UnicodeData.txt')
    ap.add_argument('--out', default=str(ROOT / 'keysyms.cst'))
    args = ap.parse_args()

    rx = re.compile(r'^#define XKB_KEY_(\w+)\s+0x([0-9a-fA-F]+)\s*(/\*.*?\*/)?', re.M)
    names = []
    table = {}
    for m in rx.finditer(Path(args.header).read_text()):
        name, ks, comment = m.group(1), int(m.group(2), 16), m.group(3) or ''
        names.append((name, ks))
        u = re.match(r'/\*\s*[(<]?U\+([0-9A-F]{4,6})', comment)
        if u and ks not in table:
            table[ks] = int(u.group(1), 16)
    table.update(UCS_OVERRIDES)

    def ucs(ks):
        r = rule_ucs(ks)
        return table.get(ks, 0) if r is None else r

    # Only what the rules do not already say goes in the table.
    ucs_rows = sorted((ks, cp) for ks, cp in table.items() if rule_ucs(ks) is None and cp)

    upper, lower = {}, {}
    for line in Path(args.unicode_data).read_text().splitlines():
        f = line.split(';')
        cp = int(f[0], 16)
        if f[12]:
            upper[cp] = int(f[12], 16)
        if f[13]:
            lower[cp] = int(f[13], 16)

    # A character's first legacy keysym, keysyms in order.
    legacy_of = {}
    for ks in sorted({ks for _, ks in names}):
        if ks <= LEGACY_CASE_MAX or 0xfd00 <= ks <= 0xffff:
            cp = ucs(ks)
            if cp:
                legacy_of.setdefault(cp, ks)

    def legacy_case(ks, mapping):
        cp = ucs(ks)
        if not cp or cp not in mapping:
            return ks
        to = mapping[cp]
        if to in legacy_of:
            return legacy_of[to]
        return to if to < 0x100 else to + UNICODE_OFFSET

    legacy_rows = []
    for ks in range(0, LEGACY_CASE_MAX + 1):
        up = UPPER_OVERRIDES.get(ks, legacy_case(ks, upper))
        lo = legacy_case(ks, lower)
        if up != ks or lo != ks:
            legacy_rows.append((ks, up, lo))
    unicode_rows = sorted((cp, upper.get(cp, cp), lower.get(cp, cp))
                          for cp in set(upper) | set(lower) if cp >= 0x100)

    names.sort(key=lambda e: e[0].encode())
    blob = bytearray()
    index = bytearray()
    for name, ks in names:
        index += struct.pack('<II', len(blob), ks)
        blob += name.encode() + b'\0'

    def lit(data):
        return '"' + ''.join('\\x%02x' % b for b in data) + '"'

    def rows(fmt, items):
        out = bytearray()
        for item in items:
            out += struct.pack(fmt, *item)
        return out

    text = f'''// GENERATED by input/xkb/tools/gen_keysyms.py from {Path(args.header).name}
// and UnicodeData.txt. DO NOT EDIT. Regenerate from the repository root:
//   python3 input/xkb/tools/gen_keysyms.py
//
// N_NAMES names, NUL-terminated in NAMES, sorted by byte; NAME_INDEX per name:
// u32 offset into NAMES, u32 keysym. UCS: keysym → character where no rule
// of keysym.cst says it, u32 pairs sorted by keysym. LEGACY_CASE: legacy
// keysyms up to 0x13be whose case differs — keysym, upper, lower, u32 each.
// UNICODE_CASE: code points from 0x100 with a simple case mapping — code
// point, upper, lower. All little-endian.

let is i64 as N_NAMES with imut = {len(names)};
let is i64 as N_UCS with imut = {len(ucs_rows)};
let is i64 as N_LEGACY_CASE with imut = {len(legacy_rows)};
let is i64 as N_UNICODE_CASE with imut = {len(unicode_rows)};

let is *u8 as NAMES with imut = {lit(blob)};
let is *u8 as NAME_INDEX with imut = {lit(index)};
let is *u8 as UCS with imut = {lit(rows('<II', ucs_rows))};
let is *u8 as LEGACY_CASE with imut = {lit(rows('<III', legacy_rows))};
let is *u8 as UNICODE_CASE with imut = {lit(rows('<III', unicode_rows))};
'''
    Path(args.out).write_text(text)
    print(f'{args.out}: {len(names)} names, {len(ucs_rows)} characters, '
          f'{len(legacy_rows)} legacy and {len(unicode_rows)} Unicode case rows')


if __name__ == '__main__':
    main()
